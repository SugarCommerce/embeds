	/**
	 * The platform's mark as an inline SVG element.
	 *
	 * `currentColor` and no stroke, so the mark takes the colour of the link
	 * around it and a hover state needs no second rule. Hidden from screen
	 * readers: the link it sits in carries the name, and a reader announcing
	 * "image" before it is noise.
	 *
	 * @since 1.1.0
	 *
	 * @param string $class Classes for sizing and colour, e.g. `h-5 w-5`.
	 *                      '' for none.
	 *
	 * @return string
	 */
	public function icon( string $class = '' ): string {
		return sprintf(
			'<svg%s viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="%s"/></svg>',
			'' === $class ? '' : ' class="' . htmlspecialchars( $class, ENT_QUOTES, 'UTF-8' ) . '"',
			htmlspecialchars( $this->icon_path(), ENT_QUOTES, 'UTF-8' )
		);
	}

	/**
	 * Every embed origin, for a content security policy.
	 *
	 * Generated from the cases rather than written out again, so adding a
	 * platform cannot leave a policy behind.
	 *
	 * @since 1.0.0
	 *
	 * @param array<int, self> $only Limit to these platforms. Empty means all.
	 *
	 * @return array<int, string>
	 */
	public static function origins( array $only = array() ): array {
		$cases = $only ?: self::cases();

		return array_values( array_unique( array_filter( array_map(
			static fn( self $platform ): string => $platform->origin(),
			$cases
		) ) ) );
	}
